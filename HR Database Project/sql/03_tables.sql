USE Store;
GO

CREATE TABLE dbo.STORE (
    STORE_CODE       INT           NOT NULL CONSTRAINT PK_STORE PRIMARY KEY,
    STORE_NAME       VARCHAR(50)   NOT NULL,
    STORE_YTD_SALES  DECIMAL(12,2) NOT NULL,
    CONSTRAINT CK_STORE_YTD_SALES CHECK (STORE_YTD_SALES > 0)
);

CREATE TABLE dbo.EMPLOYEE (
    Employee_ID       CHAR(5)      NOT NULL CONSTRAINT PK_EMPLOYEE PRIMARY KEY,
    Employee_FName    VARCHAR(25)  NOT NULL,
    Employee_LName    VARCHAR(25)  NOT NULL,
    Employee_HireDate DATE         NOT NULL,
    Employee_Title    VARCHAR(30)  NOT NULL,
    EMP_CODE          INT          NOT NULL
        CONSTRAINT DF_EMPLOYEE_EMP_CODE DEFAULT (NEXT VALUE FOR dbo.seq_emp_code)
        CONSTRAINT UQ_EMPLOYEE_EMP_CODE UNIQUE,
    STORE_CODE        INT          NOT NULL
        CONSTRAINT DF_EMPLOYEE_STORE_CODE DEFAULT (3),
    CONSTRAINT FK_EMPLOYEE_STORE FOREIGN KEY (STORE_CODE)
        REFERENCES dbo.STORE (STORE_CODE)
);

CREATE TABLE dbo.SKILL (
    Skill_ID          INT           NOT NULL CONSTRAINT PK_SKILL PRIMARY KEY,
    Skill_Name        VARCHAR(50)   NOT NULL,
    Skill_Description VARCHAR(200)  NOT NULL
);

CREATE TABLE dbo.CERTIFIED (
    Employee_ID    CHAR(5) NOT NULL,
    Skill_ID       INT     NOT NULL,
    Certified_Date DATE    NOT NULL,
    CONSTRAINT PK_CERTIFIED PRIMARY KEY (Employee_ID, Skill_ID),
    CONSTRAINT FK_CERTIFIED_EMPLOYEE FOREIGN KEY (Employee_ID)
        REFERENCES dbo.EMPLOYEE (Employee_ID),
    CONSTRAINT FK_CERTIFIED_SKILL FOREIGN KEY (Skill_ID)
        REFERENCES dbo.SKILL (Skill_ID)
);
GO